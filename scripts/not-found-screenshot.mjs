import { chromium } from "playwright";
import { join } from "path";
const b = await chromium.launch({ headless: true });
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1.5, colorScheme: "dark" });
const p = await ctx.newPage();
await p.goto("http://localhost:3000/en/this-page-does-not-exist", { waitUntil: "networkidle", timeout: 15000 });
await p.waitForTimeout(1200);
await p.screenshot({ path: join(process.cwd(), "ph-screenshots", "16-not-found.png") });
console.log("✓ 404 page");
await b.close();
