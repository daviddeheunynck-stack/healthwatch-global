import { chromium } from "playwright";
import { join } from "path";
const b = await chromium.launch({ headless: true });
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1, colorScheme: "dark" });
const p = await ctx.newPage();
await p.goto("http://localhost:3000/en/login", { waitUntil: "networkidle", timeout: 15000 });
await p.waitForTimeout(1500);
await p.screenshot({ path: join(process.cwd(), "ph-screenshots", "13-login-en.png") });
console.log("✓ login-en");
await b.close();
