// Print-optimized outbreak one-pager
// Opens in a new tab → user prints/saves as PDF via browser
// URL: /fr/outbreak/{id}/print

import { createClient } from "@supabase/supabase-js";
import { notFound } from "next/navigation";
import { getLocalizedDisease, getLocalizedCountry } from "@/lib/outbreaks";
import { getIncidenceRate, getPopulationThousands } from "@/lib/population-data";
import type { Metadata } from "next";

const BOM   = String.fromCharCode(65279);
const clean = (v: string | undefined) => (v || "").replace(new RegExp("^" + BOM), "").trim();

export async function generateMetadata({ params }: { params: Promise<{ locale: string; id: string }> }): Promise<Metadata> {
  const { id } = await params;
  return {
    title: `Outbreak Report — HealthWatch Global`,
    robots: { index: false, follow: false },
  };
}

